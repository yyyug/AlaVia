#!/usr/bin/env node

import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawn } from "node:child_process";

const CKAN_SEARCH_URL = "https://ckan.hokonavi.go.jp/api/3/action/package_search?rows=200";
const R2_BUCKET = "alavia-cache";
const dryRun = process.argv.includes("--dry-run");
const production = process.argv.includes("--env") && process.argv[process.argv.indexOf("--env") + 1] === "production";
const manifestJsonPath = "scripts/hokonavi-dp-manifest.json";
const manifestTsPath = "src/data/hokonavi-dp-manifest.ts";

async function main() {
  const tempDir = await mkdtemp(join(tmpdir(), "alavia-hokonavi-dp-"));
  try {
    const catalog = await fetchJson(CKAN_SEARCH_URL);
    const packages = catalog.result.results.filter((item) => String(item.name).startsWith("nwd_"));
    if (packages.length !== 28) throw new Error(`Expected 28 nwd_* datasets, received ${packages.length}`);

    const datasets = [];
    for (const [index, pkg] of packages.sort((a, b) => a.name.localeCompare(b.name)).entries()) {
      const nodeResource = findGeoJsonResource(pkg.resources, "node.geojson");
      const linkResource = findGeoJsonResource(pkg.resources, "link.geojson");
      console.log(`[${index + 1}/28] ${pkg.name}`);
      const [nodeText, linkText] = await Promise.all([fetchText(nodeResource.url), fetchText(linkResource.url)]);
      const graph = buildGraph(pkg.name, JSON.parse(nodeText), JSON.parse(linkText));
      validateGraph(pkg.name, graph);
      const bounds = calculateBounds(graph.nodes);
      const metadata = {
        id: pkg.name,
        title: pkg.title,
        sourceLabel: "ほこナビ DP",
        updatedAt: extractUpdatedAt(pkg.notes) || String(pkg.metadata_modified || "").slice(0, 10),
        catalogUrl: `https://ckan.hokonavi.go.jp/dataset/${pkg.name}`,
        nodeUrl: nodeResource.url,
        linkUrl: linkResource.url,
        bounds,
        nodeCount: graph.nodes.length,
        edgeCount: graph.edges.length,
      };
      datasets.push(metadata);
      console.log(`  nodes=${graph.nodes.length} edges=${graph.edges.length}`);

      if (!dryRun) {
        const datasetDir = join(tempDir, pkg.name);
        await mkdir(datasetDir, { recursive: true });
        const nodePath = join(datasetDir, "node.geojson");
        const linkPath = join(datasetDir, "link.geojson");
        const graphPath = join(datasetDir, "graph.json");
        await Promise.all([
          writeFile(nodePath, nodeText),
          writeFile(linkPath, linkText),
          writeFile(graphPath, JSON.stringify(graph)),
        ]);
        await uploadR2(`hokonavi-dp/raw/${pkg.name}/node.geojson`, nodePath);
        await uploadR2(`hokonavi-dp/raw/${pkg.name}/link.geojson`, linkPath);
        await uploadR2(`hokonavi-dp/normalized/${pkg.name}/graph.json`, graphPath);
      }
    }

    const manifest = {
      source: "hokonavi-dp",
      sourceLabel: "ほこナビ DP",
      generatedAt: new Date().toISOString(),
      datasetCount: datasets.length,
      datasets,
    };
    await mkdir("src/data", { recursive: true });
    await writeFile(manifestJsonPath, `${JSON.stringify(manifest, null, 2)}\n`);
    await writeFile(manifestTsPath, `// Generated by scripts/sync-hokonavi-dp.mjs. Do not edit manually.\nexport const HOKONAVI_DP_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`);
    if (!dryRun) {
      const manifestPath = join(tempDir, "manifest.json");
      await writeFile(manifestPath, JSON.stringify(manifest));
      await uploadR2("hokonavi-dp/manifest.json", manifestPath);
    }
    console.log(`${dryRun ? "Validated" : "Uploaded"} ${datasets.length} Hokonavi DP walking-network datasets.`);
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

function findGeoJsonResource(resources, filename) {
  const resource = resources.find((item) => item.format === "GeoJSON" && String(item.url).endsWith(`/${filename}`));
  if (!resource) throw new Error(`Missing ${filename}`);
  return resource;
}

function extractUpdatedAt(notes) {
  return String(notes || "").match(/最終更新日:\s*(\d{4}\/\d{2}\/\d{2})/)?.[1]?.replaceAll("/", "-") || null;
}

async function fetchJson(url) {
  return JSON.parse(await fetchText(url));
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed ${response.status}: ${url}`);
  return response.text();
}

function buildGraph(datasetId, nodeCollection, linkCollection) {
  const nodes = new Map();
  for (const feature of nodeCollection.features || []) {
    const properties = feature.properties || {};
    const nodeId = String(properties.node_id || "").trim();
    const coordinates = feature.geometry?.coordinates;
    const lon = Number(Array.isArray(coordinates) ? coordinates[0] : properties.lon);
    const lat = Number(Array.isArray(coordinates) ? coordinates[1] : properties.lat);
    if (!nodeId || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    nodes.set(nodeId, {
      id: `hokonavi-dp-node:${datasetId}:${nodeId}`,
      lat: round6(lat),
      lon: round6(lon),
      kind: classifyNode(properties),
      label: null,
      level: formatFloor(properties.floor),
      source: "hokonavi-dp",
      properties: { ...properties, datasetId, sourceLabel: "ほこナビ DP" },
    });
  }

  const edges = [];
  for (const feature of linkCollection.features || []) {
    const properties = feature.properties || {};
    const linkId = String(properties.link_id || "").trim();
    const from = nodes.get(String(properties.start_id || "").trim());
    const to = nodes.get(String(properties.end_id || "").trim());
    if (!linkId || !from || !to) continue;
    const direction = Number(properties.direction);
    const shared = {
      distanceMeters: nullableNumber(properties.distance),
      kind: classifyEdge(properties),
      requiresConfirmation: requiresConfirmation(properties, from, to),
      source: "hokonavi-dp",
      properties: { ...properties, datasetId, sourceLabel: "ほこナビ DP" },
    };
    if (direction !== 3) edges.push(makeEdge(datasetId, linkId, "forward", from, to, shared));
    if (direction !== 2) edges.push(makeEdge(datasetId, linkId, "reverse", to, from, shared));
  }
  return { nodes: [...nodes.values()], edges };
}

function makeEdge(datasetId, linkId, suffix, from, to, shared) {
  return {
    id: `hokonavi-dp-link:${datasetId}:${linkId}:${suffix}`,
    from: from.id,
    to: to.id,
    bearing: Math.round(bearingDegrees(from, to)),
    level: from.level === to.level ? from.level : `${from.level || "?"}->${to.level || "?"}`,
    ...shared,
  };
}

function validateGraph(datasetId, graph) {
  if (!graph.nodes.length || !graph.edges.length) throw new Error(`${datasetId}: empty graph`);
  const ids = new Set(graph.nodes.map((node) => node.id));
  const invalid = graph.edges.filter((edge) => !ids.has(edge.from) || !ids.has(edge.to));
  if (invalid.length) throw new Error(`${datasetId}: ${invalid.length} edges have missing endpoints`);
}

function calculateBounds(nodes) {
  const lats = nodes.map((node) => node.lat);
  const lons = nodes.map((node) => node.lon);
  return { minLat: Math.min(...lats), maxLat: Math.max(...lats), minLon: Math.min(...lons), maxLon: Math.max(...lons) };
}

function classifyNode(properties) {
  if (Number(properties.in_out) === 2) return "facility_boundary";
  if (Number(properties.in_out) === 3) return "facility_interior";
  return "pedestrian_node";
}

function classifyEdge(properties) {
  const routeType = Number(properties.route_type);
  const structure = Number(properties.rt_struct);
  if (routeType === 2) return "moving_walkway";
  if (routeType === 4) return "elevator";
  if (routeType === 5) return "escalator";
  if (routeType === 6) return "stairs";
  if (routeType === 7) return "ramp";
  if (structure === 5) return "underground_passage";
  if (structure === 6) return "footbridge";
  if (structure === 7) return "facility_corridor";
  return "pedestrian_path";
}

function requiresConfirmation(properties, from, to) {
  const routeType = Number(properties.route_type);
  return Number(properties.rt_struct) === 99
    || routeType === 99
    || Number(from.properties.in_out) !== Number(to.properties.in_out)
    || from.level !== to.level
    || [4, 5, 6].includes(routeType);
}

function formatFloor(value) {
  const floor = Number(value);
  return Number.isFinite(floor) ? String(floor) : null;
}

function nullableNumber(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function round6(value) {
  return Math.round(value * 1_000_000) / 1_000_000;
}

function bearingDegrees(from, to) {
  const p1 = from.lat * Math.PI / 180;
  const p2 = to.lat * Math.PI / 180;
  const lambda = (to.lon - from.lon) * Math.PI / 180;
  const y = Math.sin(lambda) * Math.cos(p2);
  const x = Math.cos(p1) * Math.sin(p2) - Math.sin(p1) * Math.cos(p2) * Math.cos(lambda);
  return (Math.atan2(y, x) * 180 / Math.PI + 360) % 360;
}

function uploadR2(key, file) {
  const args = ["wrangler", "r2", "object", "put", `${R2_BUCKET}/${key}`, "--file", file, "--remote"];
  if (production) args.push("--env", "production");
  return run("npx", args);
}

function run(command, args) {
  return new Promise((resolve, reject) => {
    const executable = process.platform === "win32" ? `${command}.cmd` : command;
    const child = spawn(executable, args, { stdio: "inherit" });
    child.on("exit", (code) => code === 0 ? resolve() : reject(new Error(`${command} exited with ${code}`)));
    child.on("error", reject);
  });
}

await main();
